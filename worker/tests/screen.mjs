import assert from 'node:assert/strict';
import { mock } from 'node:test';
import { createServer } from 'vite';
import { createPinia, setActivePinia, disposePinia } from 'pinia';
import { nextTick } from 'vue';
const vite=await createServer({server:{middlewareMode:true},appType:'custom'});
const pinia=createPinia();setActivePinia(pinia);
let checks=0;
const check=(name,fn)=>{fn();checks++;console.log(`✓ ${name}`);};
const originalImage=globalThis.Image;
globalThis.Image=class {naturalWidth=1568;naturalHeight=1015;async decode(){}};
try {
    const {useWsStore}=await vite.ssrLoadModule('/src/stores/ws.js');
    const {useScreenStore}=await vite.ssrLoadModule('/src/stores/screen.js');
    const ws=useWsStore(),handlers=new Map(),messages=[];
    ws.onMessage=(type,fn)=>handlers.set(type,fn);
    ws.sendMsg=(message)=>{messages.push(message);return true;};
    ws.devices=[{id:'one',online:true},{id:'two',online:true}];ws.currentDeviceId='one';ws.state='connected';ws.authenticated=true;
    mock.timers.enable({apis:['setTimeout','Date'],now:10000});
    const screen=useScreenStore();
    const requests=()=>messages.filter((m)=>m.type==='screen.request');
    const last=()=>requests().at(-1);
    const settle=async()=>{for(let i=0;i<12;i++)await Promise.resolve();await nextTick();};
    const reply=(message,extra={})=>handlers.get('screen.result')({meta:{deviceId:message.to.slice(7)},data:{reqId:message.data.reqId,ok:true,frameId:'frame-'+message.data.reqId,mime:'image/jpeg',data:'aW1hZ2U=',capturedAt:Date.now(),control:{supported:true,allowed:true},...extra}});
    screen.start();
    check('进入屏幕页面立即截图',()=>assert.equal(last().data.action,'capture'));
    mock.timers.tick(8000);
    check('慢截图期间不发送重叠请求',()=>assert.equal(requests().length,1));
    reply(last());await settle();
    mock.timers.tick(200);await settle();
    check('截图完成后按周期继续刷新',()=>assert.equal(requests().length,2));
    const late=last(),before=screen.frame.id;
    screen.stop();
    reply(late);await settle();mock.timers.tick(60000);
    check('离开应用取消在途请求，停止刷新并丢弃迟到结果',()=>{assert.equal(requests().length,2);assert.equal(screen.frame.id,before);assert.ok(messages.some((m)=>m.type==='screen.cancel'&&m.data.reqId===late.data.reqId));});
    screen.start();
    check('返回页面后先取新画面，再允许操作',()=>assert.equal(screen.canControl,false));
    reply(last());await settle();assert.equal(screen.canControl,true);mock.timers.tick(2000);await settle();
    const poll=last();
    const operation=screen.operate({type:'click',x:0.5,y:0.5,button:'left',count:1});
    check('操作前取消正在进行的周期截图',()=>{assert.equal(last().data.action,'input');assert.ok(messages.some((m)=>m.type==='screen.cancel'&&m.data.reqId===poll.data.reqId));});
    const amount=requests().length;
    mock.timers.tick(4000);await settle();
    check('操作等待期间不截图',()=>assert.equal(requests().length,amount));
    reply(last());await settle();assert.equal(await operation,true);
    mock.timers.tick(249);assert.equal(requests().length,amount);
    mock.timers.tick(1);await settle();
    check('操作成功后自动刷新画面',()=>{assert.equal(requests().length,amount+1);assert.equal(last().data.action,'capture');});
    reply(last());await settle();screen.setAutomatic(false);
    const paused=requests().length;mock.timers.tick(60000);
    check('暂停自动刷新后不再定时截图',()=>assert.equal(requests().length,paused));
    const text=screen.operate({type:'text',text:'中文🙂'});reply(last());await settle();await text;mock.timers.tick(250);await settle();
    check('暂停定时刷新后，操作仍会刷新结果',()=>assert.equal(last().data.action,'capture'));
    const oldDevice=last();ws.currentDeviceId='two';await settle();reply(oldDevice);await settle();
    check('切换设备清除旧画面，结果不会串设备',()=>{assert.equal(last().to,'device:two');assert.equal(screen.frame,null);});
    reply(last());await settle();screen.setVisible(false);const hidden=requests().length;mock.timers.tick(60000);
    check('网页切到后台停止刷新',()=>assert.equal(requests().length,hidden));
    screen.setVisible(true);await settle();check('回到网页立即更新截图',()=>assert.equal(requests().length,hidden+1));
    reply(last(),{control:{supported:true,allowed:false}});await settle();
    const blocked=requests().length;assert.equal(await screen.operate({type:'text',text:'不可执行'}),false);
    check('未授权辅助功能时可以查看，不能发送控制命令',()=>{assert.equal(screen.canControl,false);assert.ok(screen.frame);assert.equal(requests().length,blocked);});
    screen.setAutomatic(true);reply(last(),{ok:false,error:'截图失败'});await settle();
    const failed=requests().length;mock.timers.tick(60000);
    check('截图失败暂停自动重试，不反复弹权限提示',()=>{assert.equal(requests().length,failed);assert.equal(screen.captureError,'截图失败');});
    const manual=screen.refresh();reply(last());await settle();await manual;
    ws.state='offline';await settle();const disconnected=requests().length;mock.timers.tick(60000);
    check('断线停止请求，重连后补一张最新画面',()=>{assert.equal(requests().length,disconnected);});
    ws.state='connected';await settle();assert.equal(requests().length,disconnected+1);
    screen.stop();
    console.log(`\n${checks} 项屏幕会话检查全部通过`);
} finally {mock.timers.reset();globalThis.Image=originalImage;disposePinia(pinia);await vite.close();}
